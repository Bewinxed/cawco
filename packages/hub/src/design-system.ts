const KEPT_WHY =
  "The person changed it since CawCo wrote it (or CawCo never wrote it), so it stays as they have it. Say in your hand-in what you would change in it.";

/** The call's files by their path in `design/`; refused whole, every problem named, when one does not hold. */
const incomingFiles = (files: DesignFile[]): Map<string, Uint8Array> => {
  const problems: string[] = [];
  const incoming = new Map<string, Uint8Array>();
  for (const file of files) {
    const named = designPath(file.path);
    if ("problem" in named) {
      problems.push(named.problem);
      continue;
    }
    try {
      const body = folderContent(file.content, file.encoding);
      incoming.set(
        named.path,
        typeof body === "string" ? encoder.encode(body) : body
      );
    } catch (error) {
      problems.push(
        `${named.path}: ${error instanceof Error ? error.message : String(error)}`
      );
    }
  }
  if (problems.length > 0) {
    throw new Error(`Nothing was written. ${problems.join(" ")}`);
  }
  return incoming;
};

/**
 * The token system built from what the files will hold (the call's writes
 * over what is there), once every token has its source; the problems said
 * otherwise.
 */
const systemOf = async (
  file: (path: string) => Promise<Uint8Array | null>,
  manifest: DesignManifest,
  problems: string[]
): Promise<BuiltTokens | undefined> => {
  try {
    const built = await buildDesignTokens(async (path) => {
      const bytes = await file(path);
      if (!bytes) {
        throw new Error(
          `${path} is named by ${RESOLVER} but is not in design/`
        );
      }
      return JSON.parse(decoder.decode(bytes));
    });
    const unsourced = [...built.system.files]
      .filter(([path]) => path !== RESOLVER)
      .flatMap(([, json]) => [...tokensIn(json)].map((token) => token.path))
      .filter((path, at, all) => all.indexOf(path) === at)
      .filter((path) => !manifest.sources[path]?.trim());
    if (unsourced.length > 0) {
      problems.push(
        `These tokens have no source in manifest.json: ${unsourced.join(", ")}. Every value traces to something you read, a decision page card, or the person's edit.`
      );
    }
    return built;
  } catch (error) {
    problems.push(
      `The tokens do not build: ${error instanceof Error ? error.message : String(error)}`
    );
  }
};

/**
 * The token system the files will hold, built, when there is one: refused
 * (in `problems`) when token files come without the resolver, or before
 * any manifest.
 */
const tokensOf = async (at: {
  contentOf: (path: string) => Promise<Uint8Array | null>;
  hasManifest: boolean;
  manifest: DesignManifest | undefined;
  paths: string[];
  problems: string[];
}): Promise<BuiltTokens | undefined> => {
  const there = async (path: string) => (await at.contentOf(path)) !== null;
  const tokenFiles = at.paths.filter(isTokenFile);
  const present = await Promise.all(tokenFiles.map(there));
  const hasTokens = present.some(Boolean);
  const resolverThere = await there(RESOLVER);
  if (hasTokens && !resolverThere) {
    at.problems.push(
      `Write ${RESOLVER} with the token files: it names the base set and each theme's file.`
    );
  }
  if (hasTokens && at.manifest && !at.hasManifest) {
    at.problems.push(
      "Write manifest.json first, or in the same call: every token needs its source."
    );
  }
  return resolverThere && at.manifest
    ? await systemOf(at.contentOf, at.manifest, at.problems)
    : undefined;
};

/** What a write would put in design/, worked out and not yet written. */
interface DesignPlan {
  kept: Set<string>;
  out: { path: string; bytes: Uint8Array }[];
  /** Whether a path holds a file once `out` is written. */
  there: (path: string) => boolean;
}

/**
 * What writing `files` into a system would write: the person's files kept,
 * tokens.json checked against the manifest (every token has a source),
 * tokens.css generated from it, the manifest's fingerprints recorded.
 * Refused whole, with every problem, when a path, the manifest or the
 * tokens do not hold.
 */
const planDesign = async (
  store: DesignStore,
  files: DesignFile[]
): Promise<DesignPlan> => {
  const incoming = incomingFiles(files);
  const problems: string[] = [];
  const current = await store.read([
    ...new Set([...DESIGN_PARTS, ...incoming.keys()]),
  ]);
  const now = (path: string) => current.get(path) ?? null;
  const recordedBytes = now(MANIFEST);
  const recorded = recordedBytes
    ? (manifestOf(recordedBytes, []) ?? { sources: {}, files: {} })
    : { sources: {}, files: {} };
  /** The person's: there, and not as CawCo last wrote it. */
  const theirs = (path: string): boolean => {
    const bytes = now(path);
    return bytes !== null && recorded.files[path] !== fingerprint(bytes);
  };

  // The manifest is the hub's ledger, merged below; every other file is
  // written unless the person's.
  const others = [...incoming].filter(([path]) => path !== MANIFEST);
  const kept = new Set(
    others.filter(([path]) => theirs(path)).map(([path]) => path)
  );
  const writes = new Map(others.filter(([path]) => !kept.has(path)));

  const given = incoming.get(MANIFEST);
  const manifest = given ? manifestOf(given, problems) : recorded;
  const contentOf = async (path: string): Promise<Uint8Array | null> =>
    writes.get(path) ??
    (current.has(path)
      ? now(path)
      : ((await store.read([path])).get(path) ?? null));
  const built = await tokensOf({
    contentOf,
    hasManifest: Boolean(given || recordedBytes),
    manifest,
    paths: [...writes.keys(), ...current.keys()],
    problems,
  });
  if (problems.length > 0) {
    throw new Error(`Nothing was written. ${problems.join(" ")}`);
  }
  // Settled values go into the files the call wrote, and into CawCo's own
  // files it left; never into the person's.
  for (const [path, json] of built?.changed ?? []) {
    if (!(kept.has(path) || theirs(path))) {
      writes.set(path, encoder.encode(`${JSON.stringify(json, null, 2)}\n`));
    }
  }
  // The generated files: each written when it changed, kept when the person's.
  const generated: [string, string][] = built
    ? [
        [STYLESHEET, built.css],
        [TYPES, built.types],
      ]
    : [];
  for (const [path, text] of generated) {
    const bytes = encoder.encode(text);
    const before = now(path);
    if (theirs(path)) {
      kept.add(path);
    } else if (!(before && Buffer.from(before).equals(bytes))) {
      writes.set(path, bytes);
    }
  }

  const fingerprints = { ...recorded.files };
  for (const [path, bytes] of writes) {
    fingerprints[path] = fingerprint(bytes);
  }
  const ledger: DesignManifest = {
    sources: (manifest ?? recorded).sources,
    files: Object.fromEntries(
      Object.entries(fingerprints).sort(([a], [b]) => a.localeCompare(b))
    ),
  };
  const out = [
    ...[...writes].map(([path, bytes]) => ({ path, bytes })),
    {
      path: MANIFEST,
      bytes: encoder.encode(`${JSON.stringify(ledger, null, 2)}\n`),
    },
  ];
  return {
    out,
    kept,
    there: (path) =>
      out.some((file) => file.path === path) || now(path) !== null,
  };
};

/** Writes `files` into a system ({@link planDesign}), and says what it wrote and kept. */
export const writeDesign = async (
  store: DesignStore,
  files: DesignFile[]
): Promise<DesignWritten> => {
  const { out, kept, there } = await planDesign(store, files);
  await store.write(out);
  return {
    where: store.where,
    written: out.map((file) => `${DESIGN_DIR}/${file.path}`),
    kept: [...kept].map((path) => ({
      path: `${DESIGN_DIR}/${path}`,
      why: KEPT_WHY,
    })),
    missing: DESIGN_PARTS.filter((path) => !there(path)).map(
      (path) => `${DESIGN_DIR}/${path}`
    ),
  };
};

/** The longest a file's text is drawn on a proposal's card. */
const PREVIEW_CHARS = 60_000;
/** Bytes that are text: UTF-8 with no NUL. */
const textOf = (bytes: Uint8Array | null): string | null => {
  if (!bytes) {
    return "";
  }
  if (bytes.includes(0)) {
    return null;
  }
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    // Not UTF-8: drawn as binary.
    return null;
  }
};
const drawn = (bytes: Uint8Array | null): string => {
  const text = textOf(bytes);
  if (text === null) {
    return `(binary, ${bytes?.length ?? 0} bytes)\n`;
  }
  return text.length > PREVIEW_CHARS
    ? `${text.slice(0, PREVIEW_CHARS)}\n… (cut here)\n`
    : text;
};

/**
 * What writing `files` would change, drawn for the person: each file it
 * writes, before and after, the hub's ledger (manifest.json) left out when
 * only its fingerprints change. Refused as the write would be.
 */
export const previewDesign = async (
  store: DesignStore,
  files: DesignFile[]
): Promise<DesignProposalFile[]> => {
  const { out } = await planDesign(store, files);
  const before = await store.read(out.map((file) => file.path));
  const sourcesOf = (bytes: Uint8Array | null | undefined): string =>
    JSON.stringify(bytes ? (manifestOf(bytes, [])?.sources ?? null) : null);
  return out
    .filter(
      (file) =>
        file.path !== MANIFEST ||
        sourcesOf(before.get(MANIFEST)) !== sourcesOf(file.bytes)
    )
    .map((file) => ({
      path: `${DESIGN_DIR}/${file.path}`,
      before: drawn(before.get(file.path) ?? null),
      after: drawn(file.bytes),
    }))
    .filter((file) => file.before !== file.after);
};

/**
 * Runs a command on a machine in `cwd`: inside `workspace`'s boundary when
 * one is named (the hub's `runOnMachine`).
 */
export type Run = (
  machineId: string,
  cwd: string,
  cmd: string,
  timeoutMs: number,
  workspace?: WorkspaceRef
) => Promise<CommandResult>;

/**
 * A repository a system is in: its root on a machine, and, when the root is
 * a live workspace's clone, that workspace. Every command in a live clone
 * runs inside its boundary (core safe-git.ts: "A git call in a live
 * workspace's clone also runs inside the workspace's boundary"): one on the
 * host would write the clone under the boundary's read-only binds, and its
 * guard stops the boundary, the session in it with it.
 */
export interface RepositoryAt {
  machineId: string;
  root: string;
  workspace?: WorkspaceRef;
}

/** A command in a repository, where it must run ({@link RepositoryAt}). */
export const runIn =
  (run: Run, at: RepositoryAt) =>
  (cmd: string, timeoutMs = COMMAND_MS): Promise<CommandResult> =>
    run(at.machineId, at.root, cmd, timeoutMs, at.workspace);

const COMMAND_MS = 60_000;
/** Base64 per command, well under one shell argument's 128 KiB. */
const CHUNK = 64 * 1024;

const failed = (what: string, result: CommandResult): Error =>
  new Error(
    `${what}: ${(result.stderr.trim() || result.stdout.trim() || `exit ${result.exitCode}`).split("\n").slice(-4).join(" ")}`
  );

/** One file's bytes at `<target>.cawco-<index>`, in base64 chunks one shell command each. */
const writeTemporary = async (
  sh: ReturnType<typeof runIn>,
  file: { path: string; bytes: Uint8Array },
  index: number
): Promise<void> => {
  const target = `${DESIGN_DIR}/${file.path}`;
  const text = Buffer.from(file.bytes).toString("base64");
  const count = Math.max(1, Math.ceil(text.length / CHUNK));
  for (let part = 0; part < count; part += 1) {
    const chunk = text.slice(part * CHUNK, (part + 1) * CHUNK);
    const head =
      part === 0 ? `mkdir -p ${quote(posix.dirname(target))} && ` : "";
    // biome-ignore lint/performance/noAwaitInLoops: one chunk after another, in order
    const result = await sh(
      `${head}printf %s '${chunk}' | base64 -d ${part === 0 ? ">" : ">>"} ${quote(`${target}.cawco-${index}`)}`
    );
    if (result.exitCode !== 0) {
      throw failed(`${target} could not be written`, result);
    }
  }
};

/**
 * A system at a repository's root on a machine, read and written with its
 * shell, inside its workspace's boundary when it is one, git run the safe
 * way (core `SAFE_GIT_SHELL`). `base` is the commit a system must be on to
 * be the project's: a workspace's base branch on origin, else the
 * checkout's HEAD.
 */
const repositoryStore = (
  run: Run,
  at: RepositoryAt,
  base = "HEAD"
): DesignStore => {
  const sh = runIn(run, at);
  return {
    where: `${at.root}/${DESIGN_DIR}`,
    theirs: async () => {
      const result = await sh(
        `${SAFE_GIT_SHELL}git rev-parse --verify -q ${quote(`${base}^{commit}`)} >/dev/null || { echo "${base} is not a commit here" >&2; exit 2; }; if git cat-file -e ${quote(`${base}:${DESIGN_DIR}/${MANIFEST}`)} 2>/dev/null; then echo yes; else echo no; fi`
      );
      if (result.exitCode !== 0) {
        throw failed("design/'s history could not be read", result);
      }
      return result.stdout.trim() === "yes";
    },
    commit: async (message) => {
      const result = await sh(
        `${SAFE_GIT_SHELL}git add -A -- ${DESIGN_DIR} && { git diff --cached --quiet -- ${DESIGN_DIR} || git commit -q -m ${quote(message)} -- ${DESIGN_DIR}; } && git rev-parse HEAD`
      );
      if (result.exitCode !== 0) {
        throw failed("design/ could not be committed", result);
      }
      return result.stdout.trim().split("\n").at(-1) ?? "";
    },
    read: async (paths) => {
      const result = await sh(
        `for p in ${paths.map((path) => quote(`${DESIGN_DIR}/${path}`)).join(" ")}; do if [ -f "$p" ]; then printf 'F\\t%s\\t' "$p"; base64 < "$p" | tr -d '\\n'; echo; fi; done`
      );
      if (result.exitCode !== 0) {
        throw failed("design/ could not be read", result);
      }
      const found = new Map<string, Uint8Array | null>(
        paths.map((path) => [path, null])
      );
      for (const line of result.stdout.split("\n")) {
        const [mark, path, body] = line.split("\t");
        if (mark === "F" && path) {
          found.set(
            path.slice(DESIGN_DIR.length + 1),
            new Uint8Array(Buffer.from(body ?? "", "base64"))
          );
        }
      }
      return found;
    },
    write: async (files) => {
      // Each file to a temporary name first, then all moved into place.
      for (const [index, file] of files.entries()) {
        // biome-ignore lint/performance/noAwaitInLoops: one file after another
        await writeTemporary(sh, file, index);
      }
      const moved = await sh(
        files
          .map(
            (file, index) =>
              `mv -f ${quote(`${DESIGN_DIR}/${file.path}.cawco-${index}`)} ${quote(`${DESIGN_DIR}/${file.path}`)}`
          )
          .join(" && ")
      );
      if (moved.exitCode !== 0) {
        throw failed("design/ could not be written", moved);
      }
    },
  };
};

/** The trailer naming the session whose write a folder commit of design/ is. */
const SESSION_TRAILER = "Session";

/**
 * A system in a project's folder on the hub, each write its own commit by
 * `author` carrying the writing session's trailer: the session that first
 * committed design/manifest.json there is the system's builder, and to any
 * other session the system is the project's.
 */
const folderStore = (
  projectId: string,
  author: string,
  changed: (projectId: string) => void,
  session: string,
  message = "design: write the design system"
): DesignStore => ({
  where: `${projectRoot(projectId)}/${DESIGN_DIR}`,
  theirs: () => {
    const read = Bun.spawnSync(
      [
        "git",
        "log",
        "--diff-filter=A",
        "--reverse",
        `--format=%(trailers:key=${SESSION_TRAILER},valueonly)%x00`,
        "--",
        `${DESIGN_DIR}/${MANIFEST}`,
      ],
      { cwd: projectRoot(projectId) }
    );
    if (read.exitCode !== 0) {
      // A folder git has no history for yet holds no system.
      return Promise.resolve(false);
    }
    // A record a commit (`%x00` ends each), the oldest first; none: no system.
    const out = read.stdout.toString();
    if (!out.includes("\0")) {
      return Promise.resolve(false);
    }
    // Committed by another session, by the person, or before trailers: the project's.
    return Promise.resolve(out.split("\0")[0]?.trim() !== session);
  },
  // Every folder write is its own commit already.
  commit: () =>
    Promise.resolve(
      Bun.spawnSync(["git", "-C", projectRoot(projectId), "rev-parse", "HEAD"])
        .stdout.toString()
        .trim()
    ),
  read: async (paths) =>
    new Map(
      await Promise.all(
        paths.map(async (path): Promise<[string, Uint8Array | null]> => {
          try {
            const file = await readFolderBytes(
              projectId,
              `${DESIGN_DIR}/${path}`,
              FOLDER_FILE_LIMIT
            );
            return [path, file.bytes];
          } catch (error) {
            if (error instanceof FolderRefusal && error.status === 404) {
              return [path, null];
            }
            throw error;
          }
        })
      )
    ),
  write: async (files) => {
    await writeFolderFiles(
      projectId,
      files.map((file) => ({
        path: `${DESIGN_DIR}/${file.path}`,
        content: file.bytes,
      })),
      {
        author: { name: author },
        message: `${message}\n\n${SESSION_TRAILER}: ${session}`,
      }
    );
    changed(projectId);
  },
});

/** What `git status` says of design/ that is not committed, a path a line. */
const UNCOMMITTED = `git status --porcelain --untracked-files=all -- ${DESIGN_DIR}`;
/** How many uncommitted paths a refusal names. */
const NAMED = 5;

const uncommittedLine = (
  where: string,
  porcelain: string
): string | undefined => {
  const paths = porcelain
    .split("\n")
    .map((line) => line.slice(3).trim())
    .filter(Boolean);
  if (paths.length === 0) {
    return;
  }
  const named = paths.slice(0, NAMED).join(", ");
  const more = paths.length > NAMED ? ` and ${paths.length - NAMED} more` : "";
  return `design/ isn't committed in ${where}: ${named}${more}. Send it back so the builder commits it, then approve.`;
};

/** The ref a workspace's base branch is on origin as: what the project has, apart from the workspace's own commits. */
export const baseRef = (base: string): string => `refs/remotes/origin/${base}`;

/**
 * Whether the workspace clone at `root` on `machineId` holds a design
 * system on its base branch (`base`): the project's, which its session
 * changes only through proposals and whose work is judged against it. One
 * the session's own commits made is its build.
 */
export const designOnBase = (
  run: Run,
  workspace: { base: string; id: string; machineId: string; path: string }
): Promise<boolean> =>
  repositoryStore(
    run,
    {
      machineId: workspace.machineId,
      root: workspace.path,
      workspace: { id: workspace.id, path: workspace.path },
    },
    baseRef(workspace.base)
  ).theirs();

/** What an attempt reads first of the system, and what it fetches on demand (spec §5.7, "Use"; Open Design's order). */
const READ_FIRST = `Read \`${DESIGN_DIR}/DESIGN.md\` and \`${DESIGN_DIR}/${STYLESHEET}\` first; \`${DESIGN_DIR}/${RESOLVER}\`, \`${DESIGN_DIR}/${MANIFEST}\`, fonts and specimens only as the work needs them.`;

/**
 * An attempt's brief's `## Design system` section (dispatch.ts): the
 * project's system as the attempt's clone holds it, design/ at its root,
 * read inside its boundary as every command in a live clone is. Its usage
 * guide (design/SKILL.md) whole, then what to read first. Empty when the
 * clone holds no design/.
 */
export const designSection = async (
  run: Run,
  clone: { id: string; machineId: string; path: string }
): Promise<string> => {
  const read = await runIn(run, {
    machineId: clone.machineId,
    root: clone.path,
    workspace: { id: clone.id, path: clone.path },
  })(
    `if [ -d ${DESIGN_DIR} ]; then echo system; if [ -f ${DESIGN_DIR}/SKILL.md ]; then cat ${DESIGN_DIR}/SKILL.md; fi; fi`
  );
  if (read.exitCode !== 0) {
    throw failed("design/ could not be read in the attempt's clone", read);
  }
  const [mark, ...rest] = read.stdout.split("\n");
  if (mark !== "system") {
    return "";
  }
  const guide = rest.join("\n").trim();
  return [
    "## Design system",
    guide
      ? `This project has a design system, at \`${DESIGN_DIR}/\` in your clone. Its usage guide, \`${DESIGN_DIR}/SKILL.md\`:`
      : `This project has a design system, at \`${DESIGN_DIR}/\` in your clone.`,
    ...(guide ? [guide] : []),
    READ_FIRST,
  ].join("\n\n");
};

/** The longest a proposal's reason runs: its commit's subject carries it. */
const WHY_LIMIT = 500;

/**
 * Where a session's design/ is: a repository ({@link RepositoryAt}), with the
 * commit a system must be on to be the project's (`base`), or the project's
 * folder (`repo` null). A proposal goes back here on Approve.
 */
interface ProposalPlace {
  base?: string;
  repo: RepositoryAt | null;
}

export const createDesignSystem = (deps: {
  run: Run;
  ownMachineId: Promise<string>;
  folderChanged: (projectId: string) => void;
  db: Pick<
    DbShape,
    | "designChecks"
    | "getInstancesByIds"
    | "listAgents"
    | "project"
    | "projectAttempts"
    | "workItem"
    | "workspacesNamed"
  >;
  online: (machineId: string) => boolean;
  /** Whether a task is design work (design-offers.ts `designShaped`, or the build itself). */
  designTask: (projectId: string, taskId: string) => Promise<boolean>;
  /** Parks an ask for the person: the pending ledger, every dashboard, push. */
  park: (envelope: Envelope) => void;
  /** Takes a settled ask off the pending ledger. */
  settle: (requestId: string) => void;
  /** A word from the hub to a session (work-items.ts `tellSession`). */
  tell: (instanceId: string, content: string) => void;
}) => {
  /** Open proposals, by id. */
  const open = new Set<string>();
  /**
   * Why your approval of a design task waits: its newest attempt's
   * workspace, while it stands, or the project's folder on the hub holds
   * design/ changes no commit has. A workspace retired after landing has
   * none (landing refuses uncommitted work).
   */
  const approvalRefusal = async (
    projectId: string,
    taskId: string
  ): Promise<string | undefined> => {
    if (!(await deps.designTask(projectId, taskId))) {
      return;
    }
    const folder = projectRoot(projectId);
    if (existsSync(join(folder, DESIGN_DIR))) {
      const read = Bun.spawnSync([
        "git",
        "-C",
        folder,
        "status",
        "--porcelain",
        "--untracked-files=all",
        "--",
        DESIGN_DIR,
      ]);
      const line = uncommittedLine(
        "the project's folder",
        read.stdout.toString()
      );
      if (line) {
        return line;
      }
    }
    const [attempt] = deps.db
      .projectAttempts(projectId)
      .filter((item) => item.taskId === taskId);
    const [workspace] = attempt
      ? deps.db.workspacesNamed(attempt.workspaceId)
      : [];
    if (!workspace || workspace.state === "archived") {
      return;
    }
    if (!deps.online(workspace.machineId)) {
      return `The builder's workspace is on ${machineCalled(workspace.machineId, deps.db.listAgents())}, which is offline, so CawCo can't read whether its design/ is committed. Approve once that machine is back.`;
    }
    // A live clone is read inside its boundary (core safe-git.ts).
    // A live attempt's clone is read inside its boundary; a finished one's,
    // whose boundary is closing with it, on the host (core safe-git.ts).
    const read = await deps.run(
      workspace.machineId,
      workspace.path,
      `${SAFE_GIT_SHELL}${UNCOMMITTED}`,
      COMMAND_MS,
      isLive(attempt?.state ?? "done")
        ? { id: workspace.id, path: workspace.path }
        : undefined
    );
    if (read.exitCode !== 0) {
      return `CawCo couldn't read the builder's workspace (${(read.stderr || read.stdout).trim().split("\n").at(-1)}), so whether its design/ is committed is unknown. Try Approve again.`;
    }
    return uncommittedLine("the builder's workspace", read.stdout);
  };

  /** Where a session's design/ is: its project's folder, or the root of the repository it works in. */
  const placeOf = async (actor: InstanceRow): Promise<ProposalPlace> => {
    if (!actor.projectId) {
      throw new Error(
        "A design system belongs to a project; this session is in none."
      );
    }
    const folder = projectRoot(actor.projectId);
    if (
      actor.machineId === (await deps.ownMachineId) &&
      (actor.cwd === folder || actor.cwd.startsWith(`${folder}/`))
    ) {
      return { repo: null };
    }
    // A work item's session works in its workspace's clone, read inside its
    // boundary; the project's system there is what its base branch holds on
    // origin, never its own commits.
    const own = workspaceOfSession(actor.id);
    const workspace = own && !own.ended ? own.workspace : undefined;
    const top = await deps.run(
      actor.machineId,
      actor.cwd,
      `${SAFE_GIT_SHELL}git rev-parse --show-toplevel`,
      COMMAND_MS,
      workspace && { id: workspace.id, path: workspace.path }
    );
    const root = top.stdout.trim();
    if (top.exitCode !== 0 || !root) {
      throw new Error(
        `${actor.cwd} is not inside a repository, so design/ has no root to go at. Work from the project's repository or its folder.`
      );
    }
    const inClone = workspace?.path === root ? workspace : undefined;
    return {
      repo: {
        machineId: actor.machineId,
        root,
        ...(inClone
          ? { workspace: { id: inClone.id, path: inClone.path } }
          : {}),
      },
      ...(inClone ? { base: baseRef(inClone.base) } : {}),
    };
  };

  /**
   * The workspace a session's work item runs in, while that item is live:
   * its boundary stands, and every command in its clone runs inside it.
   * `ended` when the item has finished (its boundary closing with it); none
   * for a session that runs no item.
   */
  const workspaceOfSession = (instanceId: string) => {
    const [row] = deps.db.getInstancesByIds([instanceId]);
    const item = row?.workItemId ? deps.db.workItem(row.workItemId) : undefined;
    const [workspace] = item ? deps.db.workspacesNamed(item.workspaceId) : [];
    return workspace && item
      ? { workspace, ended: !isLive(item.state) }
      : undefined;
  };

  /**
   * The store at a place, written for `session`: the folder's writes
   * committed by `author` with `message`.
   */
  const storeAt = (
    projectId: string,
    place: ProposalPlace,
    session: string,
    author: string,
    message?: string
  ): DesignStore =>
    place.repo
      ? repositoryStore(deps.run, place.repo, place.base)
      : folderStore(projectId, author, deps.folderChanged, session, message);

  /** The proposal as the person's ask: drawn as its diff, answered by Approve or Deny, where it was made too. */
  const envelopeOf = (row: DesignProposalRow, project: string): Envelope => ({
    verb: "frames",
    machineId: "hub",
    instanceId: row.id,
    requestId: row.id,
    payload: {
      kind: "permission_request",
      instanceId: row.id,
      requestId: row.id,
      harness: "claude",
      requestKind: "tool",
      toolName: DESIGN_PROPOSAL_TOOL,
      input: { files: row.preview, why: row.why, project },
      designProposal: row.id,
      projectId: row.projectId,
      proposer: `Design system · ${project}`,
      raisedAt: row.createdAt.getTime(),
      originInstanceId: row.instanceId,
      ...(row.toolUseId ? { toolUseId: row.toolUseId } : {}),
    },
  });

  const park = (row: DesignProposalRow): void => {
    const project = deps.db.project(row.projectId);
    if (!project) {
      return;
    }
    open.add(row.id);
    deps.park(envelopeOf(row, project.name));
  };

  /**
   * An agent's change to a system its project already had: kept, and parked
   * for the person with its diff. design/ stays as it is until they approve.
   */
  const propose = async (
    actor: InstanceRow,
    projectId: string,
    place: ProposalPlace,
    files: DesignFile[],
    rawWhy: string | undefined,
    toolUseId: string | undefined
  ) => {
    const why = rawWhy?.trim() ?? "";
    if (!why) {
      throw new Error(
        "Nothing was written. This changes the project's design system, which goes to the person as a proposal: say why, in one line (why)."
      );
    }
    if (why.length > WHY_LIMIT) {
      throw new Error(
        `Nothing was written. why is ${why.length} characters long; say it in one line, under ${WHY_LIMIT}.`
      );
    }
    const preview = await previewDesign(
      storeAt(projectId, place, actor.id, boardTitle(actor)),
      files
    );
    if (preview.length === 0) {
      throw new Error(
        "Nothing was written: design/ already holds exactly that."
      );
    }
    const row: DesignProposalRow = {
      id: `dp-${crypto.randomUUID()}`,
      projectId,
      instanceId: actor.id,
      machineId: place.repo?.machineId ?? null,
      root: place.repo?.root ?? null,
      why,
      files,
      preview,
      toolUseId: toolUseId ?? null,
      createdAt: new Date(),
    };
    deps.db.designChecks.propose(row);
    park(row);
    console.log(
      `[design] ${projectId}: ${row.id} proposes ${preview.map((file) => file.path).join(", ")}`
    );
    return {
      proposal: row.id,
      files: preview.map((file) => file.path),
      waiting:
        "design/ is unchanged: the person sees this in Needs you with its diff, and you're told their answer. Approved, it is written and committed here.",
    };
  };

  /**
   * Where an approved proposal is written: its repository, inside its
   * proposing session's workspace's boundary when that clone is the
   * repository, or the project's folder. Refused, saying so, when that
   * session's work item has ended (nothing would land a commit in its clone
   * any more) or its machine is offline.
   */
  const placeOfProposal = (row: DesignProposalRow): ProposalPlace => {
    if (!(row.machineId && row.root)) {
      return { repo: null };
    }
    if (!deps.online(row.machineId)) {
      throw new Error(
        `The proposal's repository is on ${machineCalled(row.machineId, deps.db.listAgents())}, which is offline. Approve once it is back.`
      );
    }
    const own = workspaceOfSession(row.instanceId);
    if (own?.workspace.path !== row.root) {
      return { repo: { machineId: row.machineId, root: row.root } };
    }
    const { workspace } = own;
    if (own.ended) {
      throw new Error(
        `The work item that proposed this has ended, so nothing would land a commit in ${row.root} any more. Deny it; the change can be proposed again.`
      );
    }
    return {
      repo: {
        machineId: row.machineId,
        root: row.root,
        workspace: { id: workspace.id, path: workspace.path },
      },
    };
  };

  /** Approve: written through design_write where it was proposed, and committed. Answers the commit. */
  const apply = async (row: DesignProposalRow): Promise<string> => {
    const place = placeOfProposal(row);
    const message = `design: ${row.why}\n\nProposal: ${row.id}`;
    const store = storeAt(
      row.projectId,
      place,
      row.instanceId,
      YOU.name,
      message
    );
    await writeDesign(store, row.files);
    return await store.commit(message);
  };

  return {
    approvalRefusal,

    /**
     * `design_write`: a system the session is building itself is written at
     * once; a change to the project's ({@link DesignStore.theirs}) is a
     * proposal the person approves.
     */
    write: async (
      actor: InstanceRow,
      files: DesignFile[],
      why: string | undefined,
      toolUseId: string | undefined
    ): Promise<DesignWritten | Awaited<ReturnType<typeof propose>>> => {
      const place = await placeOf(actor);
      const projectId = actor.projectId as string;
      const store = storeAt(projectId, place, actor.id, actor.title ?? "CawCo");
      if (await store.theirs()) {
        return propose(actor, projectId, place, files, why, toolUseId);
      }
      return writeDesign(store, files);
    },

    /** Whether `requestId` is a design proposal waiting on the person. */
    owns: (requestId: string): boolean => open.has(requestId),

    /**
     * The person's answer: approved, it is written and committed where it
     * was proposed; denied, design/ stays as it was. Either way its session
     * is told and the ask leaves the ledger; a write that fails throws, and
     * its ask stays.
     */
    async answer(requestId: string, result: PermissionResult): Promise<void> {
      const row = deps.db.designChecks.proposal(requestId);
      if (row) {
        const files = row.preview.map((file) => file.path).join(", ");
        if (result.behavior === "allow") {
          // A write that fails leaves the ask parked; its reason is said here
          // and to the person's answer.
          const sha = await apply(row).catch((error: unknown) => {
            console.warn(
              `[design] ${row.projectId}: ${row.id} was approved and not written: ${error instanceof Error ? error.message : String(error)}`
            );
            throw error;
          });
          console.log(
            `[design] ${row.projectId}: ${row.id} approved, committed as ${sha.slice(0, 9)}`
          );
          deps.tell(
            row.instanceId,
            `The person approved your design proposal ${row.id} (${files}): it is written and committed as ${sha.slice(0, 9)} in ${row.root ?? "the project's folder"}.`
          );
        } else {
          const reason = result.message.trim();
          deps.tell(
            row.instanceId,
            `The person declined your design proposal ${row.id} (${files})${reason ? `: “${reason}”` : ""}. design/ is as it was; nothing was written.`
          );
        }
        deps.db.designChecks.dropProposal(row.id);
      }
      open.delete(requestId);
      deps.settle(requestId);
    },

    /** Every open proposal, parked again as the hub starts: the person's asks outlive it. */
    start: (): void => {
      for (const row of deps.db.designChecks.proposals()) {
        park(row);
      }
    },
  };
};

export type DesignSystem = ReturnType<typeof createDesignSystem>;
