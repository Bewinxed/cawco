/**
 * A project's design system on disk (Projects spec §5.7, "Design files, as
 * needed"): the `design/` folder a builder session makes from the project's
 * own material, and the one way it is written, the `design_write` tool.
 *
 * Where it lives (owner, 2026-10-16, Q1): at the root of the repository the
 * session works in, so every place and workspace has it; in the project's
 * folder on the hub when that folder is where the session works, committed
 * there as any folder write is.
 *
 * The folder contract:
 *   DESIGN.md              the prose guide: the visual-foundations answers, rules, recipes
 *   tokens.resolver.json   the DTCG 2025.10 resolver: the base set, then each theme as a
 *                          modifier's context (dtcg-resolver.ts)
 *   tokens.json            the base set, DTCG 2025.10 values, named for the project's own roles
 *   themes/*.tokens.json   each context's overrides (dark, a coarse pointer…)
 *   tokens.css             generated here from the resolver on every write, never by hand
 *   tokens.ts              generated with it: `TokenColor`, `TokenSize`, `TokenFont`, the
 *                          system's names, which a component's props take to be offered them
 *   manifest.json         `sources`: where each token's value came from (the builder's);
 *                          `files`: the fingerprint of every file CawCo wrote (the hub's)
 *   SKILL.md               routes any harness to the system
 *   specimens/index.html   the Foundations page, on ../tokens.css
 *   fonts/ assets/ references/ explorations/   as the work needs them
 *
 * Every write settles the token files (a recipe token's static `$value`
 * computed, design-tokens.ts `settle`) and checks them against the DTCG
 * schemas. Regeneration never overwrites a file the person edited: a file
 * whose bytes no longer match the fingerprint CawCo recorded when it wrote
 * it (or that CawCo never wrote) is kept as it is and listed as kept. No
 * preset, no fixed token vocabulary, no scan of values (plan §4): the one
 * deterministic step is generating tokens.css and tokens.ts, a build, not a
 * judgment.
 */
