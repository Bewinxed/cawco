/**
 * `bun scripts/stage-glyphs.ts [--check]`: the decision-page kit's stage
 * glyphs (packages/hub/skills/decision-page/kit/stage-glyphs.js), the same
 * Solar duotone glyphs the board draws a stage's mark in (stage-look.ts), by
 * the plain word stages.md names each by (core `STAGE_ICONS`), with each
 * one's name and each colour's (core `stageLookWords`). A setup page is a
 * page of its own with no Svelte or icon build behind it, so the kit carries
 * each glyph's SVG body, read from the icon set the dashboard draws.
 * `--check` fails when the file is not what this writes.
 */
import { join } from "node:path";
import { STAGE_COLORS, type StageIcon } from "@cawco/core/views";
import { stageLookWords } from "@cawco/core/words/onboarding";
import solar from "@iconify-json/solar/icons.json" with { type: "json" };

/** Each stage glyph's Solar name: the one its `STAGE_GLYPHS` component imports (packages/icons). */
const SOLAR: Record<StageIcon, string> = {
  inbox: "documents-bold-duotone",
  idea: "magic-stick-3-bold-duotone",
  search: "magnifer-bold-duotone",
  pen: "pen-bold-duotone",
  chat: "chat-square-bold-duotone",
  eye: "eye-bold-duotone",
  clock: "clock-circle-bold-duotone",
  hourglass: "hourglass-bold-duotone",
  calendar: "calendar-bold-duotone",
  send: "plain-2-bold-duotone",
  rocket: "rocket-2-bold-duotone",
  code: "code-2-bold-duotone",
  palette: "pallete-2-bold-duotone",
  graph: "course-up-bold-duotone",
  user: "user-bold-duotone",
  globe: "global-bold-duotone",
  book: "book-bold-duotone",
  pin: "pin-bold-duotone",
  bolt: "bolt-bold-duotone",
  list: "list-check-bold-duotone",
  lab: "test-tube-bold-duotone",
  map: "map-point-bold-duotone",
  phone: "smartphone-bold-duotone",
  money: "dollar-bold-duotone",
  done: "check-bold-duotone",
  archive: "archive-down-minimlistic-bold-duotone",
  trash: "trash-bin-minimalistic-bold-duotone",
};

const icons = solar.icons as Record<string, { body: string }>;
const glyphs = Object.entries(SOLAR).map(([word, name]) => {
  const icon = icons[name];
  if (!icon) {
    throw new Error(`Solar has no ${name} (stage glyph ${word}).`);
  }
  return [
    word,
    { name: stageLookWords.icons[word as StageIcon], body: icon.body },
  ];
});
const colors = STAGE_COLORS.map((color) => [
  color,
  stageLookWords.colors[color],
]);

const text = `// Generated by apps/dashboard/scripts/stage-glyphs.ts from core's stage
// looks and the icon set the dashboard draws. Do not edit: run it again.
window.cawcoStageLook = ${JSON.stringify(
  { glyphs: Object.fromEntries(glyphs), colors: Object.fromEntries(colors) },
  null,
  2
)};
`;

const OUT = join(
  import.meta.dir,
  "../../../packages/hub/skills/decision-page/kit/stage-glyphs.js"
);
if (process.argv.includes("--check")) {
  const now = await Bun.file(OUT)
    .text()
    .catch(() => "");
  if (now !== text) {
    console.error(
      "stage-glyphs: the decision-page kit's stage-glyphs.js is not what core's stage looks make; run `bun scripts/stage-glyphs.ts` in apps/dashboard."
    );
    process.exit(1);
  }
  console.log(`stage-glyphs: ${glyphs.length} glyphs, as the kit has them`);
} else {
  await Bun.write(OUT, text);
  console.log(`stage-glyphs: wrote ${glyphs.length} glyphs`);
}
