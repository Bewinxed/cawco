#!/usr/bin/env node
import { execFileSync } from "node:child_process";
/**
 * Emit mocks/tokens.css — the Phase 3 token system.
 *
 * Tier 1 (global) is the VERBATIM `palette.mjs` output. It is inlined by this
 * script rather than pasted by hand so that no hex value in the shipped token
 * file was ever typed by a human or a model: the only source of a colour
 * literal in this project is the generator.
 *
 * Tier 2 (alias) is derived from tier 1 with `color-mix(in oklab, …)` and
 * relative `oklch(from …)`. It exists because the generator's fixed lightness
 * spec (L_LIGHT = [0.993, 0.981, 0.956, 0.93, …]) has no step between 249 and
 * 241 mean-channel luminance, and the reference system needs a content field at
 * 244 that is simultaneously below fidelity.py's card threshold (>248) and
 * outside its band-detection window (239.5–242.5).
 *
 *   node mocks/build-tokens.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

